# Numbers

# 1. int and float
print(10)
print(3.14)

# 2. check the type
print(type(10))
print(type(3.14))

# 3. basic math
print(7 + 3)
print(7 - 3)
print(7 * 3)
print(7 / 3)

# 4. floor division, remainder, power
print(7 // 3)
print(7 % 3)
print(2 ** 5)

# 5. order of operations
print(2 + 3 * 4)
print((2 + 3) * 4)

# 6. built-in functions
print(abs(-5))
print(round(3.14159, 2))
print(max(3, 9, 4))
print(min(3, 9, 4))

# 7. change types
print(int("42") + 1)
print(float("2.5") * 2)
print(int(9.99))

# 8. math module
import math
print(math.sqrt(16))
print(math.ceil(4.1))
print(math.floor(4.9))
print(math.pi)
