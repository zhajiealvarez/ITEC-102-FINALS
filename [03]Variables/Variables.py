# Variables

# 1. make a variable
age = 20
print(age)

# 2. change the value
age = 21
print(age)

# 3. different types
name = "Ana"
height = 1.6
is_student = True
print(name, height, is_student)

# 4. type of a variable
print(type(name))
print(type(age))

# 5. many variables at once
a, b, c = 1, 2, 3
print(a, b, c)

# 6. same value for many
x = y = z = 0
print(x, y, z)

# 7. swap two variables
a, b = b, a
print(a, b)

# 8. math with variables
price = 50
quantity = 3
total = price * quantity
print("Total:", total)
