# Hello World and print()

# 1. print a message
print("Hello, world!")

# 2. print numbers and text together
print("I am", 20, "years old")

# 3. print on many lines
print("Line 1")
print("Line 2")

# 4. change the separator
print("2026", "11", "15", sep="-")

# 5. change the end
print("Loading", end="...")
print("done")

# 6. new line and tab
print("Hello\nWorld")
print("Name:\tAna")

# 7. f-string
name = "Ana"
print(f"Hello, {name}!")

# 8. multi-line text
print("""This is
a long text
on three lines""")
