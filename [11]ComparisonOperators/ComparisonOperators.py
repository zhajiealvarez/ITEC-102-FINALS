# Comparison operators

# 1. equal
print(5 == 5)
print(5 == 3)

# 2. not equal
print(5 != 3)

# 3. greater than and less than
print(7 > 3)
print(7 < 3)

# 4. greater or equal, less or equal
print(5 >= 5)
print(4 <= 3)

# 5. compare strings
print("apple" == "apple")
print("a" == "A")
print("apple" < "banana")

# 6. chained
x = 15
print(10 < x < 20)

# 7. with variables
age = 18
print(age >= 18)

# 8. with and / or
score = 75
print(score >= 50 and score <= 100)
print(score < 50 or score > 70)
